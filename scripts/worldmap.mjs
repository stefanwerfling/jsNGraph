// Builds src/widget/WorldLand.ts from Natural Earth's 1:110m land polygons (public domain,
// https://www.naturalearthdata.com — ne_110m_land.geojson). Dev-only, run once:
//   node scripts/worldmap.mjs path/to/ne_110m_land.geojson
// Antarctica is dropped (the map crops below 58° S anyway), rings are simplified
// (Douglas–Peucker, 0.25°), tiny islands dropped, coordinates quantised to 0.1° and
// stored delta + polyline-encoded (Google's algorithm) — about 10 KB.
import {readFileSync, writeFileSync} from 'node:fs';
import {join, dirname} from 'node:path';
import {fileURLToPath} from 'node:url';

const TOLERANCE = 0.25;
const MIN_AREA = 0.6;
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = process.argv[2];

if (src === undefined) {
    console.error('usage: node scripts/worldmap.mjs ne_110m_land.geojson');
    process.exit(1);
}

const data = JSON.parse(readFileSync(src, 'utf8'));
const rings = [];

for (const f of data.features) {
    const g = f.geometry;
    const polys = g.type === 'MultiPolygon' ? g.coordinates : [g.coordinates];
    for (const p of polys) {
        // outer ring only; 110m land has no lakes as holes worth keeping
        rings.push(p[0]);
    }
}

const area = (r) => {
    let a = 0;
    for (let i = 0, j = r.length - 1; i < r.length; j = i++) {
        a += (r[j][0] * r[i][1]) - (r[i][0] * r[j][1]);
    }
    return Math.abs(a / 2);
};

const simplify = (pts, tol) => {
    if (pts.length < 3) {
        return pts;
    }
    const keep = new Uint8Array(pts.length);
    keep[0] = keep[pts.length - 1] = 1;
    const stack = [[0, pts.length - 1]];
    while (stack.length) {
        const [a, b] = stack.pop();
        const [ax, ay] = pts[a];
        const [bx, by] = pts[b];
        const dx = bx - ax;
        const dy = by - ay;
        const len = Math.hypot(dx, dy) || 1;
        let best = -1;
        let idx = -1;
        for (let i = a + 1; i < b; i++) {
            const d = Math.abs((dy * (pts[i][0] - ax)) - (dx * (pts[i][1] - ay))) / len;
            if (d > best) {
                best = d;
                idx = i;
            }
        }
        if (best > tol) {
            keep[idx] = 1;
            stack.push([a, idx], [idx, b]);
        }
    }
    return pts.filter((_, i) => keep[i]);
};

const enc = (v) => {
    let n = v < 0 ? ~(v << 1) : v << 1;
    let s = '';
    while (n >= 0x20) {
        s += String.fromCharCode((0x20 | (n & 0x1f)) + 63);
        n >>= 5;
    }
    return s + String.fromCharCode(n + 63);
};

const out = [];
let points = 0;

for (const r of rings) {
    const minLat = Math.min(...r.map((p) => p[1]));
    if (minLat < -60 || area(r) < MIN_AREA) {
        continue;
    }
    // split the closed ring in two halves so the simplifier keeps a shape
    const open = r.slice(0, -1);
    const half = Math.floor(open.length / 2);
    const s = [...simplify(open.slice(0, half + 1), TOLERANCE).slice(0, -1), ...simplify([...open.slice(half), open[0]], TOLERANCE).slice(0, -1)];
    if (s.length < 3) {
        continue;
    }
    let px = 0;
    let py = 0;
    let str = '';
    for (const [lon, lat] of s) {
        const x = Math.round(lon * 10);
        const y = Math.round(lat * 10);
        str += enc(x - px) + enc(y - py);
        px = x;
        py = y;
    }
    out.push(str);
    points += s.length;
}

const body = out.map((s) => `    ${JSON.stringify(s)}`).join(',\n');
const ts = `// Generated by scripts/worldmap.mjs from Natural Earth 1:110m land (public domain). Do not edit.
// ${out.length} rings, ${points} points; each ring is delta + polyline-encoded lon/lat in 0.1°.

export const WORLD_LAND: readonly string[] = [
${body}
];
`;

writeFileSync(join(root, 'src', 'widget', 'WorldLand.ts'), ts);
console.log(`${out.length} rings, ${points} points, ${ts.length} bytes`);
